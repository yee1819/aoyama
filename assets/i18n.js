const STORE_KEY = "aoyama.lang";
// 只翻译「界面」：标题、标签、按钮、表头、提示。表格数据单元格（td）不在其中。
const ALLOW = "h1,h2,h3,h4,label,button,input,th,option,p,li,dt,dd,b,strong,span.label,.hint,.footnote,.breadcrumb,.breadcrumb a,.brand,.main-nav a,.empty,.chart-empty,.stat .label,.demo-banner,.tabs button,.card-title a,.card-title .hint,.card-title .hint a,.site-footer span,.stat .value small";
const DENY = "[data-no-i18n],td,.time,.rank,svg,.legend";

let lang = "ja";
let observer = null;

const JA_TO_ZH = new Map(DICT);
// 长词优先，避免「記録」先把「記録一覧」切碎
const KEYS = [...JA_TO_ZH.keys()].filter(Boolean).sort((a, b) => b.length - a.length);

// 「本」→「条」のような短い語を部分一致で当てると、大会名や選手名まで壊れる
// （例：日本学生陸上競技個人選手権 → 日条学生…个人选-手権）。なので
// 短いキーは「その節点まるごと」のときだけ訳し、長い語句だけ部分一致させる。
const SHORT_KEY_MAX = 3;

/** 只在日文原文上做一次替换。切回日文时直接用缓存的原文，绝不会改坏。 */
function toChinese(text) {
  const src = String(text);
  const core = src.trim();
  if (core) {
    const whole = JA_TO_ZH.get(core);
    if (whole !== undefined) return src.replace(core, whole);
  }
  let out = src;
  for (const k of KEYS) {
    if (k.length <= SHORT_KEY_MAX) continue;   // 短い語は部分一致させない
    if (out.includes(k)) out = out.split(k).join(JA_TO_ZH.get(k));
  }
  return out;
}

// 每个文本节点/属性记住日文原文
const origText = new WeakMap();
const origAttr = new WeakMap();

const inAllowed = (el) => el && el.closest && el.closest(ALLOW) === el;
const isDenied = (el) => el && el.closest && !!el.closest(DENY);

function translateElement(el) {
  if (!el || el.nodeType !== 1) return;
  if (isDenied(el) || !inAllowed(el)) return;
  for (const node of el.childNodes) {
    if (node.nodeType !== 3) continue;
    // 动态刷新过的文本（不是我们写的）→ 更新为新的日文原文
    if (node.__i18nWritten !== undefined && node.nodeValue !== node.__i18nWritten) {
      origText.set(node, node.nodeValue);
    }
    if (!origText.has(node)) origText.set(node, node.nodeValue);
    const orig = origText.get(node);
    const next = lang === "zh" ? toChinese(orig) : orig;
    if (node.nodeValue !== next) {
      node.nodeValue = next;
      node.__i18nWritten = next;
    }
  }
  let store = origAttr.get(el);
  for (const attr of ["placeholder", "title"]) {
    const cur = el.getAttribute && el.getAttribute(attr);
    if (!cur) continue;
    if (!store) { store = {}; origAttr.set(el, store); }
    const writtenKey = "__w_" + attr;
    // 外部改过的属性（不是我们写的）→ 更新原文
    if (el[writtenKey] !== undefined && cur !== el[writtenKey]) store[attr] = cur;
    if (store[attr] === undefined) store[attr] = cur;
    const next = lang === "zh" ? toChinese(store[attr]) : store[attr];
    if (cur !== next) {
      el.setAttribute(attr, next);
      el[writtenKey] = next;
    }
  }
}

export function translateTree(root = document.body) {
  if (!root) return;
  if (root.nodeType === 1) translateElement(root);
  for (const el of root.querySelectorAll(ALLOW)) {
    if (isDenied(el)) continue;
    translateElement(el);
  }
}

/** 动态内容渲染后再翻译一次 */
function observe() {
  if (observer) return;
  observer = new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === "characterData") translateElement(m.target.parentElement);
      for (const n of m.addedNodes) if (n.nodeType === 1) translateTree(n);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}

export function currentLang() { return lang; }

/** 带变量的整句：t("日本語", "中文") */
export function t(ja, zh) { return lang === "zh" ? zh : ja; }

export function setLang(next) {
  lang = next === "zh" ? "zh" : "ja";
  try { localStorage.setItem(STORE_KEY, lang); } catch { /* 隐私模式 */ }
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "ja";
  translateTree(document.body);
  renderButton();
  // 带变量的整句需要各页面自己重画
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

function renderButton() {
  const btn = document.getElementById("lang-fab");
  if (!btn) return;
  btn.textContent = lang === "zh" ? "🌐 中文" : "🌐 日本語";
  btn.title = lang === "zh" ? "日本語に切り替え" : "切换成中文";
  btn.__i18nWritten = btn.textContent;
  btn.setAttribute("data-no-i18n", "1");   // 按钮本身不参与翻译
}

/** 悬浮按钮：右下角，点一下换语言 */
export function initI18n() {
  let saved = "ja";
  try { saved = localStorage.getItem(STORE_KEY) || "ja"; } catch { /* ignore */ }
  lang = saved === "zh" ? "zh" : "ja";
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "ja";

  if (!document.getElementById("lang-fab")) {
    const btn = document.createElement("button");
    btn.id = "lang-fab";
    btn.className = "lang-fab";
    btn.type = "button";
    btn.addEventListener("click", () => setLang(lang === "zh" ? "ja" : "zh"));
    document.body.append(btn);
  }
  renderButton();
  translateTree(document.body);
  observe();
  // 有些页面会在之后才渲染，稍后再补一次
  setTimeout(() => translateTree(document.body), 300);
  setTimeout(() => translateTree(document.body), 1200);
}
